/**
 * W5 召回的题目与标准答案 —— **冻结的评测契约**。
 *
 * 三条自我约束，写在最前面，因为最容易破的就是它们：
 *   1. 题目先写、结果后跑。跑完发现某题「不该算」而删掉它，等于把分数线画在
 *      自己成绩上。要改只能整体重跑一轮并在报告里写明改了哪题、为什么。
 *   2. 每题都必须能在语料里唯一落到某篇/某节。`--verify` 会逐题回查，标错一个
 *      结论就全歪（W2 那条「14 个动作」的误标就是这么来的）。
 *   3. 问题措辞与原文用词**刻意错开**（S 组）或**刻意贴合**（K 组）。这不是随
 *      手写的：两组测的是不同的检索能力，混在一组会把结论抹平。
 *
 * ── 分组 ──────────────────────────────────────────────────────────────
 * S 组（Semantic）：问题里不含原文的关键词，用口语/同义表述问同一件事。
 *   例：语料写「颈部反应」，题面写「脖子发酸」。
 *   这一组向量检索理论上应该赢——BM25 靠字面重合，同义词直接漏。
 *
 * K 组（Keyword）：题面就是实体名（动作名），语料里原样出现。
 *   例：「史密斯窄推出现在哪次推日」，动作名逐字相同。
 *   这一组 BM25 理论上应该赢——稀疏检索在这种查询上是精确匹配，向量反而
 *   可能被语义近邻（其他推类动作）干扰。**如果向量在这组也赢，说明我的
 *   baseline 实现有问题，不是好事。**
 *
 * ── 不参与向量评测的一类 ─────────────────────────────────────────────
 * 「这个动作我多久没练了」「过去 30 天练了几次腿」这类是**数值/聚合**题：
 * 本质是集合差 + 日期比较，答案是精确数字。向量检索答不了这种题，把它算进
 * 召回率的分母会同时低估向量（拉低分数）和掩盖真问题（真正该测的语义能力
 * 被稀释）。这类走结构化查询，见 `NON_VECTOR`。
 */

export type Group = "S" | "K";

export interface Question {
  id: string;
  group: Group;
  /** 题面。用户会怎么问，就怎么写。 */
  q: string;
  /** 允许命中的文档（文件名）。命中不在这个集合里的 chunk 一律算错。 */
  docs: string[];
  /**
   * 命中章节。判定：chunk 的 headingPath 任一级含这些短语之一，**或**正文含
   * 其中之一。空数组表示只要文档对就算对（用于整篇都是答案的情况）。
   */
  section: string[];
  /** 人工从原文核过的答案要点，报告里展示用。 */
  answer: string;
  /** 这题在考什么（写报告时按这个解释结果，不事后编理由）。 */
  probes: string;
}

